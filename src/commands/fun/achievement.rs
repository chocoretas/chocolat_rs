use crate::command::{Command, CommandInfo, CommandRegistration};
use serenity::all::{Context, Message, CreateMessage, CreateEmbed, Colour};
use async_trait::async_trait;

pub struct ACHIEVEMENT;

#[async_trait]
impl Command for ACHIEVEMENT {
    fn info(&self) -> CommandInfo {
        CommandInfo {
            name: "achievement",
            description: "Crea un logro estilo Minecraft",
            category: "Fun",
        }
    }

    async fn execute(&self, ctx: &Context, msg: &Message, _args: Vec<String>) -> serenity::Result<()> {
        let embed = CreateEmbed::new()
            .colour(Colour(0x17A167))
            .description("Escribe el texto del logro.");

        msg.channel_id.send_message(&ctx.http, CreateMessage::new().embed(embed)).await?;
        Ok(())
    }
}

inventory::submit! { CommandRegistration { command: &ACHIEVEMENT } }
